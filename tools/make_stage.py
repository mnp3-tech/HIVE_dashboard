#!/usr/bin/env python3
"""Generate the stage layout from the measured spec.

Inputs : docs/hive/measurements/target.json, layout-spec.json  (see docs/hive/VISUAL_SPEC.md)
Outputs: stage-layout.css            absolute rectangles for every panel on the 1671x941 reference stage
         docs/hive/measurements/stage-layout-final.json   final rectangles + every deviation from the plan
         index.html (between the CORE markers)             the CORE SVG in reference-stage coordinates

Deviations from the measured plan are listed in DEVIATIONS and are content-driven only (<= 1.5 percentage points):
  * card row uses a uniform 14.5 px gap (measured 13-15) so the 10/16/20 px minimum gutters hold at 1280/1920/2560;
  * resources + limits panels are 10 px taller (153 vs 143): the device block and two-line captions need it;
  * the Internet label group sits 18 px lower to make room for the REQUIRED state caption under the planet.
Re-run:  python tools/make_stage.py
"""
from __future__ import annotations

import json
import math
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
M = ROOT / "docs/hive/measurements"
T = json.loads((M / "target.json").read_text())
LS = json.loads((M / "layout-spec.json").read_text())
W, H = LS["reference_stage_px"]["w"], LS["reference_stage_px"]["h"]
S = LS["scale_S"]
ring = T["core"]["neon_ring"]


def tx(x): return W / 2 + (x - ring["cx"]) * S
def ty(y): return H / 2 + (y - H / 2) * S


P = {k: dict(v) for k, v in LS["panels_px"].items()}
DEVIATIONS = []

# --- card row: measured widths, uniform 14.5 px gap, first card where the plan put it
GAP = 14.5
x = P["card_current"]["x0"]
for k in ["card_current", "card_next", "card_context", "card_external", "card_layout"]:
    old = P[k]["x0"]
    P[k]["x0"] = x
    P[k]["x1"] = x + P[k]["w"]
    x = P[k]["x1"] + GAP
    if abs(old - P[k]["x0"]) > 0.05:
        DEVIATIONS.append({"panel": k, "what": "x0", "planned": round(old, 1), "final": round(P[k]["x0"], 1), "reason": "uniform 14.5 px card gap (minimum-gutter rule at 1280/1920/2560)"})

# --- resources + limits: 10 px taller
for k in ["resources", "limits"]:
    old = P[k]["h"]
    P[k]["h"] = old + 10
    P[k]["y1"] = P[k]["y0"] + P[k]["h"]
    DEVIATIONS.append({"panel": k, "what": "h", "planned": round(old, 1), "final": round(P[k]["h"], 1), "reason": "device block / two-line captions need the height (+1.1 pp of H)"})

# --- top bar (no measurable border in the target): items span x 33..1640, y 8..48
P["topbar"] = {"x0": tx(33), "y0": ty(8), "x1": tx(1640), "y1": ty(48)}
P["topbar"]["w"] = P["topbar"]["x1"] - P["topbar"]["x0"]
P["topbar"]["h"] = P["topbar"]["y1"] - P["topbar"]["y0"]

ID = {
    "topbar": "#topbar", "chats": "#panel-chats", "projects": "#panel-projects", "agents": "#panel-agents",
    "card_current": "#card-current", "card_next": "#card-next", "card_context": "#card-context", "card_external": "#card-external", "card_layout": "#card-layout",
    "activity": "#panel-activity", "approvals": "#panel-approvals", "resources": "#panel-resources", "limits": "#panel-limits", "composer": "#chat-draft-form",
}
css = ["/* GENERATED by tools/make_stage.py from docs/hive/measurements/layout-spec.json - do not edit by hand.",
       "   Absolute rectangles on the 1671x941 reference stage (scaled by --k). Deviations: see stage-layout-final.json. */"]
for k, sel in ID.items():
    p = P[k]
    css.append(f"{sel}{{left:{p['x0']:.1f}px;top:{p['y0']:.1f}px;width:{p['w']:.1f}px;height:{p['h']:.1f}px}}")
(ROOT / "stage-layout.css").write_text("\n".join(css) + "\n")

# --- gutters actually produced (reference px)
def gap_x(a, b): return P[b]["x0"] - P[a]["x1"]
def gap_y(a, b): return P[b]["y0"] - P[a]["y1"]
gutters = {
    "chats_projects": gap_y("chats", "projects"), "projects_agents": gap_y("projects", "agents"), "activity_approvals": gap_y("activity", "approvals"),
    "resources_limits": gap_x("resources", "limits"), "cards_1_2": gap_x("card_current", "card_next"), "cards_2_3": gap_x("card_next", "card_context"),
    "cards_3_4": gap_x("card_context", "card_external"), "cards_4_5": gap_x("card_external", "card_layout"),
    "left_rail_center": P["card_current"]["x0"] - P["chats"]["x1"], "center_right_rail": P["activity"]["x0"] - P["card_layout"]["x1"],
    "resources_composer": gap_y("resources", "composer"), "topbar_cards": gap_y("topbar", "card_current"),
}
(M / "stage-layout-final.json").write_text(json.dumps({
    "reference_stage_px": {"w": W, "h": H}, "panels_px": {k: {kk: round(vv, 1) for kk, vv in v.items()} for k, v in P.items()},
    "gutters_px": {k: round(v, 1) for k, v in gutters.items()}, "deviations_from_plan": DEVIATIONS,
}, indent=1))
print("min gutter (reference px):", round(min(gutters.values()), 1), "-> at 1280x720:", round(min(gutters.values()) * 1280 / W, 2), "px")

# ----------------------------------------------------------------------------------- CORE SVG (reference coordinates)
CX, CY, R = LS["core_centre_px"]["x"], LS["core_centre_px"]["y"], LS["core_ring_radius_px"]
NODE_R = 33 * S
PLANET_R = 42 * S
HORIZON_R = T["core"]["horizon"]["r_equiv"] * S


def pol(a, r):
    return CX + R * r * math.cos(math.radians(a)), CY + R * r * math.sin(math.radians(a))


HOME = {"FURY": (-88.9, .69, "Planning", "#ffd36b"), "SHURI": (-135.5, .762, "Coding", "#b58cff"), "THOR": (-41.9, .777, "Research", "#5aa8ff"),
        "VISION": (154.6, .684, "Analysis", "#ff9a5c"), "FALCON": (25.5, .683, "Monitoring", "#6fe0ff"), "UATU": (89.8, .525, "Watching", "#8f9bff")}
f = lambda v: f"{v:.1f}"
agents = []
for name, (a, r, desc, col) in HOME.items():
    x, y = pol(a, r)
    agents.append(f'<g class="core-agent" data-agent="{name}" data-desc="{desc}" style="--role:{col}" transform="translate({f(x)} {f(y)})">'
                  f'<circle class="halo" r="{f(NODE_R + 9)}"/><circle r="{f(NODE_R)}"/><use class="ca-ico" href="#ico-{name.lower()}" x="-18" y="-18" width="36" height="36"/>'
                  f'<text class="ca-name" y="{f(NODE_R + 17)}" text-anchor="middle">{name}</text><text class="ca-state" y="{f(NODE_R + 35)}" text-anchor="middle">{desc} · UNKNOWN</text></g>')
ux, uy = pol(-88.5, .975)
px, py = pol(-30.5, 1.674)
ox, oy = pol(-162.6, 1.30)
DEVX, DEVY = 492.0, 578.0  # left of the ring so the caption (to the right of the icon) stays outside it


def label_group(gid, x0, rows, step_hint):
    items = []
    for key, label, y in rows:
        items.append(f'<g class="ctx-item" data-node="{key}" transform="translate(0 {f(y - rows[0][2])})"><circle class="ctx-dot" cx="0" cy="-5" r="4.5"/><text x="14" y="0">{label}</text></g>')
    return f'<g class="ctx-group" id="ctx-{gid}" transform="translate({f(x0)} {f(rows[0][2] + 5)})"><title>Context labels are not-observed until an event names them</title>{"".join(items)}</g>'


WEB_SHIFT = 18.0
DEVIATIONS.append({"panel": "context group: internet categories", "what": "y", "planned": 0, "final": WEB_SHIFT, "reason": "moved down to make room for the required INTERNET state caption under the planet"})
ctx = "".join([
    label_group("work", tx(473), [("files", "Files", ty(215)), ("github", "GitHub", ty(241)), ("development", "Development", ty(268))], 26),
    label_group("data", tx(482), [("data", "Data", ty(480)), ("documents", "Documents", ty(502)), ("models", "Models", ty(529))], 24),
    label_group("web", tx(1153), [(k, l, ty(y) + WEB_SHIFT) for k, l, y in [("search", "Search", 279), ("youtube", "YouTube", 303), ("news", "News", 325), ("academic", "Academic", 347), ("social_media", "Social Media", 369), ("online_tools", "Online Tools", 390)]], 22),
    label_group("sys", tx(1157), [("system", "System", ty(480)), ("security", "Security", ty(505)), ("performance", "Performance", ty(529)), ("uptime", "Uptime", ty(557))], 25),
])
hx, hy = pol(154.6, .684)
amb = [  # dim, decorative connector curves (labels -> nearest node); never data
    f"M{f(tx(473) + 110)} {f(ty(241))} C {f(tx(473) + 170)} {f(ty(241))} {f(pol(-135.5, .762)[0] - 70)} {f(pol(-135.5, .762)[1] - 6)} {f(pol(-135.5, .762)[0] - NODE_R)} {f(pol(-135.5, .762)[1])}",
    f"M{f(tx(482) + 105)} {f(ty(502))} C {f(tx(482) + 150)} {f(ty(502))} {f(hx - 90)} {f(hy + 6)} {f(hx - NODE_R)} {f(hy)}",
    f"M{f(px - PLANET_R - 4)} {f(py - 8)} C {f(px - 120)} {f(py - 36)} {f(ux + 90)} {f(uy - 14)} {f(ux + 28)} {f(uy)}",
    f"M{f(tx(1153) - 8)} {f(ty(279) + WEB_SHIFT + 20)} C {f(tx(1153) - 70)} {f(ty(279) + WEB_SHIFT + 20)} {f(pol(-41.9, .777)[0] + 80)} {f(pol(-41.9, .777)[1])} {f(pol(-41.9, .777)[0] + NODE_R)} {f(pol(-41.9, .777)[1])}",
    f"M{f(tx(1157) - 8)} {f(ty(505))} C {f(tx(1157) - 60)} {f(ty(505))} {f(pol(25.5, .683)[0] + 70)} {f(pol(25.5, .683)[1] + 4)} {f(pol(25.5, .683)[0] + NODE_R)} {f(pol(25.5, .683)[1])}",
]
cols = ["#4fe3a1", "#3fb8ff", "#ff9b4a", "#a77bff"]
ringnodes = "".join(
    f'<circle class="ring-dot big" cx="{f(pol(a, .91)[0])}" cy="{f(pol(a, .91)[1])}" r="5.5" fill="{cols[i % 4]}"/>' for i, a in enumerate([-118, -62, -4, 62, 118, 180])
) + "".join(f'<circle class="ring-dot" cx="{f(pol(a, 1.06)[0])}" cy="{f(pol(a, 1.06)[1])}" r="2.6" fill="#6fb4ff"/>' for a in range(-165, 180, 30))
VORTEX_SIZE = 2 * 0.55 * R
svg = f'''<section class="core-stage" id="core-stage" aria-label="HIVE CORE">
      <canvas id="core-canvas" class="core-arms" width="640" height="640" aria-hidden="true" style="left:{f(CX - VORTEX_SIZE / 2)}px;top:{f(CY - VORTEX_SIZE / 2)}px;width:{f(VORTEX_SIZE)}px;height:{f(VORTEX_SIZE)}px"></canvas>
      <svg id="hive-core-art" viewBox="0 0 {W} {H}" width="{W}" height="{H}" role="img" aria-label="HIVE CORE with agent roles, ULTRON ring, Obsidian and Internet nodes">
        <defs>
          <radialGradient id="vortex" cx="50%" cy="50%" r="50%"><stop offset="0" stop-color="#000"/><stop offset=".3" stop-color="#02040a"/><stop offset=".5" stop-color="#2a1366"/><stop offset=".66" stop-color="#6a2fc4" stop-opacity=".7"/><stop offset=".8" stop-color="#e0702a" stop-opacity=".55"/><stop offset=".92" stop-color="#2b8cff" stop-opacity=".3"/><stop offset="1" stop-color="#2b8cff" stop-opacity="0"/></radialGradient>
          <linearGradient id="ringGrad" gradientUnits="userSpaceOnUse" x1="{f(CX - .91 * R)}" y1="0" x2="{f(CX + .91 * R)}" y2="0"><stop offset="0" stop-color="#4fe3a1"/><stop offset=".3" stop-color="#3fb8ff"/><stop offset=".55" stop-color="#8a6cff"/><stop offset=".8" stop-color="#ff9b4a"/><stop offset="1" stop-color="#4fe3a1"/></linearGradient>
          <radialGradient id="planet" cx="38%" cy="35%" r="70%"><stop offset="0" stop-color="#9fe0ff"/><stop offset=".55" stop-color="#2b78c8"/><stop offset="1" stop-color="#06203d"/></radialGradient>
          <radialGradient id="planetAura" cx="50%" cy="50%" r="50%"><stop offset=".6" stop-color="#4aa8ff" stop-opacity="0"/><stop offset=".78" stop-color="#4aa8ff" stop-opacity=".35"/><stop offset="1" stop-color="#4aa8ff" stop-opacity="0"/></radialGradient>
          <clipPath id="planetClip"><circle r="{f(PLANET_R)}"/></clipPath>
          <filter id="glow" x="-30%" y="-30%" width="160%" height="160%"><feGaussianBlur stdDeviation="4" result="b"/><feMerge><feMergeNode in="b"/><feMergeNode in="SourceGraphic"/></feMerge></filter>
          <filter id="soft" x="-20%" y="-20%" width="140%" height="140%"><feGaussianBlur stdDeviation="3"/></filter>
        </defs>
        <g id="core-vortex-art"><circle class="core-vortex" cx="{f(CX)}" cy="{f(CY)}" r="{f(.55 * R)}" fill="url(#vortex)"/><circle class="horizon" cx="{f(CX)}" cy="{f(CY)}" r="{f(HORIZON_R)}"/><circle class="photon" cx="{f(CX)}" cy="{f(CY)}" r="{f(HORIZON_R + 3.5)}" filter="url(#glow)"/></g>
        <g class="core-ambient" id="core-ambient" aria-hidden="true">{"".join(f'<path d="{d}"/>' for d in amb)}</g>
        <g id="core-rings" aria-hidden="true">
          <circle class="core-ring ring-outer" cx="{f(CX)}" cy="{f(CY)}" r="{f(1.06 * R)}"/>
          <circle class="core-ring ring-orbit" cx="{f(CX)}" cy="{f(CY)}" r="{f(.91 * R)}" filter="url(#glow)"/>
          <circle class="core-ring ring-inner" cx="{f(CX)}" cy="{f(CY)}" r="{f(.72 * R)}"/>
          <circle class="core-ring ring-core" cx="{f(CX)}" cy="{f(CY)}" r="{f(.42 * R)}"/>
          <g id="ring-nodes">{ringnodes}</g>
        </g>
        <circle class="ultron-ring gray" id="ultron-ring" cx="{f(CX)}" cy="{f(CY)}" r="{f(R)}"/>
        <g class="core-lock" id="core-lock" hidden transform="translate({f(CX)} {f(CY)})"><rect x="-12" y="-4" width="24" height="18" rx="3"/><path d="M-7 -4 v-6 a7 7 0 0 1 14 0 v6"/></g>
        <g class="core-center" id="core-center"><text x="{f(CX)}" y="{f(CY + HORIZON_R + 24)}" text-anchor="middle" class="core-center-title">HIVE CORE</text><text x="{f(CX)}" y="{f(CY + HORIZON_R + 41)}" text-anchor="middle" class="core-center-state" id="core-center-state">UNKNOWN</text></g>
        {ctx}
        <g id="core-agents">{"".join(agents)}
        </g>
        <g class="core-agent ultron-icon" id="ultron-icon" data-agent="ULTRON" transform="translate({f(ux)} {f(uy)})"><circle r="25"/><use class="ca-ico" href="#ico-shield" x="-14" y="-14" width="28" height="28"/><text class="ca-name" y="35" text-anchor="middle">ULTRON</text></g>
        <g class="core-node" id="node-internet" transform="translate({f(px)} {f(py)})"><circle class="aura" r="{f(PLANET_R + 28)}" fill="url(#planetAura)"/><g clip-path="url(#planetClip)"><circle class="planet" r="{f(PLANET_R)}" fill="url(#planet)"/><ellipse cx="-12" cy="-4" rx="20" ry="11" fill="#3f9a5a" opacity=".55" filter="url(#soft)"/><ellipse cx="18" cy="14" rx="15" ry="8" fill="#4a9a62" opacity=".5" filter="url(#soft)"/><ellipse cx="-3" cy="-22" rx="24" ry="5" fill="#fff" opacity=".35" filter="url(#soft)"/></g><circle class="planet-rim" r="{f(PLANET_R)}"/><text class="ca-name" y="{f(PLANET_R + 22)}" text-anchor="middle">INTERNET</text><text class="ca-state" y="{f(PLANET_R + 40)}" text-anchor="middle" id="internet-state">NO ACTIVITY OBSERVED</text></g>
        <g class="core-node" id="node-obsidian" transform="translate({f(ox)} {f(oy)})"><rect x="-24" y="-24" width="48" height="48" rx="9"/><use class="ca-ico" href="#ico-gem" x="-14" y="-14" width="28" height="28"/><text class="ca-name" y="46" text-anchor="middle">OBSIDIAN</text><text class="ca-state" y="64" text-anchor="middle" id="obsidian-state">UNKNOWN</text></g>
        <g class="core-node" id="node-devices" transform="translate({f(DEVX)} {f(DEVY)})"><rect x="-22" y="-17" width="44" height="34" rx="7"/><use class="ca-ico" href="#ico-usb" x="-13" y="-13" width="26" height="26"/><text class="ca-name" x="34" y="-2" text-anchor="start">LOCAL DEVICES</text><text class="ca-state" x="34" y="16" text-anchor="start" id="devices-state">UNKNOWN</text></g>
        <g id="core-overlay"></g>
      </svg>
    </section>'''
html = (ROOT / "index.html").read_text()
a = html.index('<section class="core-stage" id="core-stage"')
b = html.index("</section>", html.index("</svg>", a)) + len("</section>")
html = html[:a] + svg + html[b:]
(ROOT / "index.html").write_text(html)
# re-write deviations (the web-group shift was appended after the first write)
d = json.loads((M / "stage-layout-final.json").read_text()); d["deviations_from_plan"] = DEVIATIONS
(M / "stage-layout-final.json").write_text(json.dumps(d, indent=1))
print("core svg + stage layout written; ring centre", round(CX, 1), round(CY, 1), "R", round(R, 1))
